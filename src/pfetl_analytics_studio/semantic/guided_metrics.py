"""Guided Explorer metric enrichment specs across investment, tax, wealth, and Silver datasets.

Owns
----
- `build_guided_enrichment_metrics()` returning `MetricSpec` entries for Guided Explorer.

Does not own
------------
- `MetricRegistry` or `DEFAULT_METRICS` singleton (owned by `semantic/metrics.py`).
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any


def _investment_segment_metrics(
    make_metric: Callable[..., Any],
    agg_cls: Any,
    fmt_cls: Any,
    prefix: str,
    dataset_id: str,
    dims: tuple[str, ...],
    *,
    include_fx: bool = False,
    include_cagr: bool = False,
) -> tuple[Any, ...]:
    """Build standardized additive + non-additive metrics for an investment segment table."""
    items: list[Any] = [
        make_metric(
            f"{prefix}_invested_value",
            "Invested Value",
            dataset_id,
            '"Total_Invested_Value"',
            agg_cls.SUM,
            fmt_cls.CURRENCY,
            "base_currency",
            dims,
            True,
            f"Cost basis invested in {dataset_id} (additive within a closing date).",
        ),
        make_metric(
            f"{prefix}_current_value",
            "Current Value",
            dataset_id,
            '"Total_Current_Value"',
            agg_cls.SUM,
            fmt_cls.CURRENCY,
            "base_currency",
            dims,
            True,
            f"Market valuation in {dataset_id} (additive within a closing date).",
        ),
        make_metric(
            f"{prefix}_unrealized_pl",
            "Unrealized P&L",
            dataset_id,
            '"Unrealized_PL"',
            agg_cls.SUM,
            fmt_cls.CURRENCY,
            "base_currency",
            dims,
            True,
            f"Total unrealized profit/loss in {dataset_id}.",
        ),
        make_metric(
            f"{prefix}_asset_pnl",
            "Asset P&L",
            dataset_id,
            '"Asset_PnL"',
            agg_cls.SUM,
            fmt_cls.CURRENCY,
            "base_currency",
            dims,
            True,
            f"Price-driven asset P&L excluding FX in {dataset_id}.",
        ),
        make_metric(
            f"{prefix}_forex_pnl",
            "Forex P&L",
            dataset_id,
            '"Forex_PnL"',
            agg_cls.SUM,
            fmt_cls.CURRENCY,
            "base_currency",
            dims,
            True,
            f"FX translation P&L contribution in {dataset_id}.",
        ),
        make_metric(
            f"{prefix}_fy_realized_net_pnl",
            "FY Realized Net P&L",
            dataset_id,
            '"FY_Realized_Net_PnL"',
            agg_cls.SUM,
            fmt_cls.CURRENCY,
            "base_currency",
            dims,
            True,
            f"Financial-year net realized P&L in {dataset_id}.",
        ),
        make_metric(
            f"{prefix}_xirr",
            "XIRR",
            dataset_id,
            '"XIRR"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"Canonical annualized XIRR in {dataset_id} (non-additive).",
        ),
        make_metric(
            f"{prefix}_after_tax_xirr",
            "After-Tax XIRR",
            dataset_id,
            '"After_Tax_XIRR"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"After-tax annualized XIRR in {dataset_id} (non-additive).",
        ),
        make_metric(
            f"{prefix}_bm_xirr",
            "Benchmark XIRR",
            dataset_id,
            '"BM_XIRR"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"Benchmark annualized XIRR in {dataset_id} (non-additive).",
        ),
        make_metric(
            f"{prefix}_active_return",
            "Active Return (Alpha)",
            dataset_id,
            '"Active_Return"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"Portfolio XIRR minus Benchmark XIRR in {dataset_id} (non-additive).",
        ),
        make_metric(
            f"{prefix}_absolute_return",
            "Absolute Return",
            dataset_id,
            '"Absolute_Return"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"Cumulative return over cost basis in {dataset_id} (non-additive).",
        ),
        make_metric(
            f"{prefix}_max_drawdown",
            "Max Drawdown",
            dataset_id,
            '"Max_Drawdown"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"Peak-to-trough drawdown in {dataset_id} (non-additive).",
        ),
        make_metric(
            f"{prefix}_weight",
            "Portfolio Weight",
            dataset_id,
            '"Weight"',
            agg_cls.LATEST,
            fmt_cls.PERCENT,
            "percent",
            dims,
            False,
            f"Share of total portfolio market value in {dataset_id} (non-additive).",
        ),
    ]
    if include_fx:
        items.extend(
            [
                make_metric(
                    f"{prefix}_xirr_local",
                    "XIRR (Local)",
                    dataset_id,
                    '"XIRR_Local"',
                    agg_cls.LATEST,
                    fmt_cls.PERCENT,
                    "percent",
                    dims,
                    False,
                    f"Local-currency XIRR in {dataset_id} (non-additive).",
                ),
                make_metric(
                    f"{prefix}_fx_xirr_impact",
                    "FX XIRR Impact",
                    dataset_id,
                    '"FX_XIRR_Impact"',
                    agg_cls.LATEST,
                    fmt_cls.PERCENT,
                    "percent",
                    dims,
                    False,
                    f"FX impact on annualized XIRR in {dataset_id} (non-additive).",
                ),
            ]
        )
    if include_cagr:
        items.append(
            make_metric(
                f"{prefix}_cagr",
                "CAGR",
                dataset_id,
                '"CAGR"',
                agg_cls.LATEST,
                fmt_cls.PERCENT,
                "percent",
                dims,
                False,
                f"Compound annual growth rate in {dataset_id} (non-additive).",
            )
        )
    return tuple(items)


